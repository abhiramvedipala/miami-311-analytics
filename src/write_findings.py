"""Write docs/findings.md and the README results table from the current database.

Usage: python src/write_findings.py
"""
import re
from pathlib import Path

from ingest import connect
from run_analysis import run_all

ROOT = Path(__file__).parent.parent
RESULTS_BLOCK = re.compile(r"<!-- results:start -->.*<!-- results:end -->", re.DOTALL)


def facts(con):
    frames = run_all(con)
    backlog = frames["04_backlog_aging"]
    flags = con.execute("SELECT * FROM mart.anomalies ORDER BY abs(z) DESC").df()
    requests, first, last = con.execute(
        "SELECT count(*), min(created_at)::date, max(created_at)::date FROM mart.fct_requests WHERE NOT is_duplicate"
    ).fetchone()
    return {
        "requests": requests,
        "first": first,
        "last": last,
        "areas": frames["02_close_time_by_neighborhood"].head(3),
        "worst": frames["01_close_time_by_type"].iloc[0],
        "backlog": int(backlog.open_requests.sum()),
        "old_share": float(backlog[backlog.age_bucket == "Over 365 days"].share_pct.sum()),
        "busiest": frames["06_weekday_hour"].sort_values("requests", ascending=False).iloc[0],
        "hotspot": frames["05_repeat_hotspots"].iloc[0] if len(frames["05_repeat_hotspots"]) else None,
        "flags": flags,
    }


def findings_text(f):
    areas = "\n".join(
        f"- {row.neighborhood}: half of requests took longer than {row.median_days} days" for row in f["areas"].itertuples()
    )
    top = "\n".join(f"- {row.note}" for row in f["flags"].head(3).itertuples())
    hotspot = f["hotspot"]
    repeat = (
        f"The strongest repeat location is in {hotspot.neighborhood}: {hotspot.requests} {hotspot.request_type} "
        f"requests, {hotspot.repeats_within_30_days} of them within 30 days of the previous one.\n"
        if hotspot is not None
        else "No repeat locations were found.\n"
    )
    return f"""# What Miami-Dade's 311 requests show

This page covers {f['requests']:,} service requests made between {f['first']} and {f['last']}. It is generated from the data by `python src/write_findings.py`.

## Where residents wait longest

{areas}

The type of request with the longest slow cases is **{f['worst'].request_type}**: one in ten took more than {f['worst'].p90_days} days to close.

These figures describe closed requests only. Requests that are still open are not counted, so true waits are longer.

## What is still open

{f['backlog']:,} requests are open, and {f['old_share']}% of them are more than a year old. Some of these may be finished work that was never marked closed, so a review of the oldest ones is the likely first step.

## Problems that keep coming back

{repeat}
Some repeats are normal, such as a household booking several bulky waste pickups. Others may point to a problem that is not being fixed.

## Unusual weeks

The three most unusual weeks were:

{top}

## When people ask for help

The busiest time is {f['busiest'].weekday} around {f['busiest'].hour}:00.

## How far to trust this

- The county changed its 311 system on 11 August 2024. Request names changed, and comparisons across that date are approximate.
- ZIP codes stand in for neighborhoods, because the data has no neighborhood field.
- Slower does not mean worse service. Areas and request types differ in the work involved.
- An unusual week lining up with a storm or holiday does not prove that it caused the change.
"""


def results_table(f):
    slowest = ", ".join(f"{row.neighborhood} ({row.median_days} days)" for row in f["areas"].itertuples())
    return f"""<!-- results:start -->
Generated by `python src/write_findings.py`. Full figures and commands are in [RESULTS.md](RESULTS.md).

| Measure | Result |
|---|---|
| Requests analysed (duplicates excluded) | {f['requests']:,} |
| Coverage | {f['first']} to {f['last']} |
| Open backlog | {f['backlog']:,} |
| 3 slowest neighborhoods, median | {slowest} |
| Worst p90 type | {f['worst'].request_type} ({f['worst'].p90_days} days) |
| Anomalous type-weeks flagged | {len(f['flags']):,} |
<!-- results:end -->"""


def main():
    con = connect()
    f = facts(con)
    con.close()
    (ROOT / "docs" / "findings.md").write_text(findings_text(f))
    readme = ROOT / "README.md"
    readme.write_text(RESULTS_BLOCK.sub(lambda _: results_table(f), readme.read_text()))


if __name__ == "__main__":
    main()
